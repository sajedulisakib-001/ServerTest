const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

/**
 * Environment & Site Configuration Generator
 */
class Configurator {
  constructor(rootDir = null) {
    this.rootDir = rootDir || path.resolve(__dirname, '..');
  }

  /**
   * Generate a cryptographically secure random secret
   */
  generateJwtSecret(bytes = 32) {
    return crypto.randomBytes(bytes).toString('hex');
  }

  /**
   * Format PostgreSQL Connection URL with production connection pooling
   */
  buildDatabaseUrl({ host = 'localhost', port = 5432, user = 'postgres', password = '', database = 'woodenmap', schema = 'public', ssl = false }) {
    const encodedUser = encodeURIComponent(user);
    const encodedPassword = encodeURIComponent(password);
    const params = [];
    if (ssl) params.push('sslmode=require');
    if (schema) params.push(`schema=${schema}`);
    params.push('connection_limit=25');
    params.push('pool_timeout=20');

    const queryStr = params.length > 0 ? `?${params.join('&')}` : '';

    if (encodedPassword) {
      return `postgresql://${encodedUser}:${encodedPassword}@${host}:${port}/${database}${queryStr}`;
    }
    return `postgresql://${encodedUser}@${host}:${port}/${database}${queryStr}`;
  }

  /**
   * Write backend/.env with strict production security standards
   */
  writeBackendEnv(config) {
    const backendEnvPath = path.join(this.rootDir, 'backend', '.env');
    const port = config.backendPort || 8585;
    let dbUrl = config.databaseUrl || 'postgresql://postgres:postgres@localhost:5433/woodenmap?schema=public';

    // Ensure connection pool params in DB URL
    if (!dbUrl.includes('connection_limit')) {
      const sep = dbUrl.includes('?') ? '&' : '?';
      dbUrl = `${dbUrl}${sep}connection_limit=25&pool_timeout=20`;
    }

    const jwtSecret = config.jwtSecret || this.generateJwtSecret(32);
    const frontendUrl = config.frontendUrl || `http://localhost:${config.frontendPort || 3000}`;

    // Ensure uploads directory exists with 0755 permissions
    const uploadsDir = path.join(this.rootDir, 'backend', 'uploads');
    if (!fs.existsSync(uploadsDir)) {
      fs.mkdirSync(uploadsDir, { recursive: true, mode: 0o755 });
    }

    const content = `# ==============================================================================
# PRODUCTION ENVIRONMENT CONFIGURATION - GENERATED BY WOODEN MIR INSTALLER
# Generated At: ${new Date().toISOString()}
# ==============================================================================

NODE_ENV=production
PORT=${port}
DATABASE_URL="${dbUrl}"
JWT_SECRET="${jwtSecret}"
FRONTEND_URL="${frontendUrl}"

# --- Payment Gateway (bKash) ---
BKASH_APP_KEY="${config.bkashAppKey || ''}"
BKASH_APP_SECRET="${config.bkashAppSecret || ''}"
BKASH_USERNAME="${config.bkashUsername || ''}"
BKASH_PASSWORD="${config.bkashPassword || ''}"
BKASH_BASE_URL="${config.bkashBaseUrl || ''}"
`;

    fs.writeFileSync(backendEnvPath, content, { encoding: 'utf8', mode: 0o600 });
    return backendEnvPath;
  }

  /**
   * Write frontend/.env.local
   */
  writeFrontendEnv(config) {
    const frontendEnvPath = path.join(this.rootDir, 'frontend', '.env.local');
    const backendPort = config.backendPort || 8585;
    const apiUrl = config.backendApiUrl || `http://localhost:${backendPort}`;

    const content = `# ==============================================================================
# FRONTEND CONFIGURATION - GENERATED BY WOODEN MIR INSTALLER
# Generated At: ${new Date().toISOString()}
# ==============================================================================

NEXT_PUBLIC_API_URL=${apiUrl}
PORT=${config.frontendPort || 3000}
`;

    fs.writeFileSync(frontendEnvPath, content, { encoding: 'utf8', mode: 0o600 });
    return frontendEnvPath;
  }

  /**
   * Create Installation Lockfile to prevent unauthorized reinstallation
   */
  createLockFile(config) {
    const lockPath = path.join(this.rootDir, 'installation', 'installed.lock');
    const lockData = {
      installed: true,
      installed_at: new Date().toISOString(),
      store_name: config.storeName || '3D Wooden World Map',
      admin_email: config.adminEmail || 'admin@woodenmap.com',
      backend_port: config.backendPort || 8585,
      frontend_port: config.frontendPort || 3000,
      installer_version: '2.0.0',
      system_arch: `${process.platform}_${process.arch}`,
      node_version: process.version,
    };

    fs.writeFileSync(lockPath, JSON.stringify(lockData, null, 2), { encoding: 'utf8', mode: 0o644 });
    return lockPath;
  }

  /**
   * Remove lockfile (used with --force)
   */
  removeLockFile() {
    const lockPath = path.join(this.rootDir, 'installation', 'installed.lock');
    if (fs.existsSync(lockPath)) {
      fs.unlinkSync(lockPath);
      return true;
    }
    return false;
  }
}

module.exports = { Configurator };
